import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  type Relation,
} from 'typeorm';
import { User } from '../../users/entities/user.entity.js';
import { Conversation } from './conversation.entity.js';

@Entity('messages')
@Index(['conversationId', 'createdAt'])
// Lets a client retry a send safely: the same (sender, clientId) is stored once.
@Index(['senderId', 'clientId'], { unique: true })
export class Message {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ type: 'uuid' })
  conversationId: string;

  @ManyToOne(() => Conversation, { onDelete: 'CASCADE' })
  @JoinColumn()
  conversation: Relation<Conversation>;

  /** The customer or a staff member. Null if that account was deleted. */
  @Column({ type: 'uuid', nullable: true })
  senderId: string | null;

  @ManyToOne(() => User, { onDelete: 'SET NULL', nullable: true })
  @JoinColumn()
  sender: Relation<User> | null;

  @Column({ type: 'text' })
  body: string;

  /** Optional id generated by the client, echoed back so it can match its optimistic bubble. */
  @Column({ type: 'uuid', nullable: true })
  clientId: string | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;
}
